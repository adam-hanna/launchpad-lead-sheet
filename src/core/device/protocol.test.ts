import { describe, expect, it } from 'vitest';
import {
  decodeLayoutMessage,
  isLaunchpadSysEx,
  layoutName,
  layoutQueryMessage,
  modeMessage,
} from './protocol';

describe('protocol', () => {
  it('builds mode and layout-query messages per the reference', () => {
    expect(modeMessage(true)).toEqual([0xf0, 0x00, 0x20, 0x29, 0x02, 0x0e, 0x0e, 0x01, 0xf7]);
    expect(modeMessage(false)).toEqual([0xf0, 0x00, 0x20, 0x29, 0x02, 0x0e, 0x0e, 0x00, 0xf7]);
    expect(layoutQueryMessage()).toEqual([0xf0, 0x00, 0x20, 0x29, 0x02, 0x0e, 0x00, 0xf7]);
  });
  it('decodes layout-changed notifications and rejects other SysEx', () => {
    expect(decodeLayoutMessage([0xf0, 0x00, 0x20, 0x29, 0x02, 0x0e, 0x00, 0x11, 0x00, 0x00, 0xf7])).toEqual({
      layout: 0x11,
      page: 0,
    });
    expect(decodeLayoutMessage([0xf0, 0x00, 0x20, 0x29, 0x02, 0x0e, 0x00, 0x03, 0x02, 0x00, 0xf7])).toEqual({
      layout: 3,
      page: 2,
    });
    expect(
      decodeLayoutMessage([0xf0, 0x00, 0x20, 0x29, 0x02, 0x0e, 0x03, 0x00, 0x0b, 0x0d, 0xf7]),
    ).toBeNull(); // LED command
    expect(
      decodeLayoutMessage([0xf0, 0x7e, 0x00, 0x06, 0x02, 0x00, 0x20, 0x29, 0x13, 0x01, 0xf7]),
    ).toBeNull(); // inquiry
    expect(decodeLayoutMessage([0xf0, 0x00, 0x20, 0x29, 0x02, 0x0e, 0x00, 0xf7])).toBeNull(); // too short (a query)
    expect(isLaunchpadSysEx([0x90, 11, 1])).toBe(false);
  });
  it('names layouts', () => {
    expect(layoutName(0x11)).toBe('Programmer');
    expect(layoutName(0x00)).toBe('Session');
    expect(layoutName(0x7f)).toBe('layout 0x7f');
  });
});
